#pragma once

// Конфигурация железа и параметров по умолчанию.
// Всё, что зависит от конкретной панели, меняется только здесь.

#include <Arduino.h>

// ---------------------------------------------------------------- Панель ---

// Пин данных светодиодной ленты (не strapping-пин, безопасен при загрузке).
#define LED_DATA_PIN 13

// Геометрия панели. Пока используется только общее число светодиодов,
// строки/столбцы понадобятся со спринта с выводом картинки.
#define PANEL_WIDTH 16
#define PANEL_HEIGHT 16
#define LED_COUNT (PANEL_WIDTH * PANEL_HEIGHT)

// Тип и порядок каналов ленты (WS2812B -> GRB).
#define LED_CHIPSET WS2812B
#define LED_COLOR_ORDER GRB

// ---------------------------------------------------------------- Питание ---

// Ограничение яркости. 255 на белом для 256 диодов - это ~15 А,
// столько блок питания стенда не отдаст.
#define DEFAULT_BRIGHTNESS 40

// Бюджет питания, FastLED сам приглушит кадр, если тот не влезает.
#define POWER_SUPPLY_VOLTS 5
#define POWER_SUPPLY_MILLIAMPS 2000

